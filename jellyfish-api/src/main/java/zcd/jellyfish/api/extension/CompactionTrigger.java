package zcd.jellyfish.api.extension;

/**
 * 压缩的触发原因：内核在问「这个会话该怎么压」时告诉插件这一次是为什么压的。
 * <p>
 * <b>为什么插件需要知道</b>：手动压与自动压的取舍不同。用户敲 {@code /compact} 是「我就要现在压，
 * 压狠一点也行」，而内核在上下文接近上限时自己压是「先保命，别丢东西」——同一套策略在两种场合下
 * 合理的答案并不一样（比如自动压时更适合保留更多原文，等用户自己决定要不要压得更狠）。
 *
 * @author zcd
 */
public enum CompactionTrigger {

    /** 用户敲了 {@code /compact}。 */
    MANUAL,

    /**
     * 内核自己触发的：上下文用量达到阈值，或本次请求已经发生机械裁剪。
     * <p>
     * 两者合并成一个取值是有意的：对插件而言「内核觉得该压了」就是全部信息，
     * 再细分成两个取值只会让插件多写一个用不上的分支。
     */
    AUTO
}

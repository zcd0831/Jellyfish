package zcd.jellyfish.api.ui;

/**
 * 界面文本段的语义种类：这一段<b>是什么</b>，而不是它长什么样。
 * <p>
 * <b>为什么除了强调档位还需要它</b>：{@link UiEmphasis} 只能表达「这段该多抢眼」，
 * 表达不了「这是一行小标题」「这是一个命令」「这是一个键值对」——而那恰恰是插件比外壳更清楚的事
 * （它自己组的那段文本是什么意思）。加上这一个字段之后，插件的面板能有一点头部、一点点代码感，
 * 而不必去猜颜色、更不必用 ANSI 转义序列污染数据。
 * <p>
 * <b>词汇表只收「纯样式」，不收「需要解析文本」的种类</b>：外壳拿到的只有「文本 + 档位 + 种类」，
 * 要画进度条得有百分比数值、要做键值对齐得知道分隔点——两者都只能去解析插件给的文本，
 * 于是同一条信息就有了两个真源（插件写的文本、外壳从中读出的数字）。因此<b>没有</b> {@code PROGRESS}：
 * 想画进度条就自己拼字符串（那本来就是内容），外壳负责的是「怎么显示」，不是「显示什么」。
 * <p>
 * <b>与强调档位正交</b>：种类决定<b>修饰</b>（粗体 / 反显 / 下划线 / 斜体），档位决定<b>颜色</b>。
 * 正交之后两者永远不会互相盖掉，插件也不必知道外壳把它们映射成了什么。
 * <p>
 * <b>种类是可扩展的，但只能由内核加</b>：新增取值会让所有外壳多一个有意义的映射，
 * 而这需要终端能力上的证据。插件用不到某个种类时，它只是一段普通文本。
 *
 * @author zcd
 */
public enum UiSegmentKind {

    /** 常规正文。 */
    TEXT,

    /** 小标题：一段面板里的分组头。 */
    HEADING,

    /** 代码 / 命令 / 标识符：最容易被误读成普通文本的内容。 */
    CODE,

    /**
     * 键值对里的<b>值</b>段。
     * <p>
     * <b>键由插件自己用 {@link #TEXT} 段写</b>：外壳只能看到一串段，无法知道哪一段是键、分隔点在哪，
     * 因此「键值对」是插件的组合而不是外壳的解析。这个种类只声明「这段是值，请把它从相邻的键里划出来」。
     */
    KEY_VALUE,

    /**
     * 可去取的东西（链接、路径、引用标识）。
     * <p>
     * <b>不写超链接转义序列</b>：终端对 OSC 8 的支持参差不齐，而这里的语义只是「这段可以去取」，
     * 不是「点它」——三外壳也没有统一的点击入口。
     */
    LINK
}

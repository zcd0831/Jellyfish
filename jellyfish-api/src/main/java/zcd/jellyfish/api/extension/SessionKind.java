package zcd.jellyfish.api.extension;

/**
 * 会话种类：说明这个会话「是怎么来的」，内核据此决定它的可见性与落盘行为。
 * <p>
 * <b>为什么要有它</b>：在此之前「是不是子代理会话」靠 {@code parentSessionId} 是不是 {@code null}
 * 来判断，而那个字段同时还要表达「派生自哪个会话」。分支（fork）出来的会话也有父，
 * 两种含义挤在同一个字段上，会把 fork 会话误判成子代理会话——后果是它<b>不落盘</b>，
 * 也就是静默的数据丢失。本类型把「判定来源」与「追溯信息」拆开：判定看本类型，
 * 追溯看 {@code parentSessionId}。
 * <p>
 * <b>不属于本类型的语义</b>：会话是否绑定了 agent、是否被压缩过、在不在当前进程的会话表里，
 * 都与它无关。
 *
 * @author zcd
 */
public enum SessionKind {

    /**
     * 用户开出来的普通会话。
     * <p>
     * 进会话列表、落盘、可被 {@code /resume} 与 {@code /delete}。
     */
    NORMAL,

    /**
     * 子代理会话：某次委派的中间产物。
     * <p>
     * <b>不进会话列表、不落盘</b>，并且随父回合结束而消失——它没有「下次回来接着用」这回事。
     * 生命周期事件照常广播（带上 {@code parentSessionId} 供订阅者归位）。
     */
    EPHEMERAL,

    /**
     * 从某个已有会话的某一点复制出来的分支会话。
     * <p>
     * <b>与普通会话同等对待</b>：进会话列表、落盘、可被 {@code /resume} 与 {@code /delete}。
     * 它是用户的会话，不是子代理的临时工作区；父会话标识与分支点消息标识只是追溯用的信息。
     */
    FORKED
}

package zcd.jellyfish.api.action;

/**
 * 动作的投递方式：插件投递一条消息时，说明它希望这条消息什么时候生效。
 * <p>
 * <b>只有两个取值，且都不是「起一个新回合」</b>：本内核里「一次 {@code chat} 调用 = 一个回合」，
 * 回合的边界由外壳决定，内核一次只知道一个回合。因此动作只能**投进正在跑的那个回合**；
 * 没有在途回合时，两个取值都当场失败（见 {@link ActionStatus#FAILED}），
 * 而不是让内核自己起一个别人不知道的回合。
 * <p>
 * 两个取值的差别是**可观察的插入点**，不是措辞：
 * <ul>
 *     <li>{@link #STEER} 插在一轮工具批次<b>之后、下一次模型调用之前</b>，
 *     因此下一轮模型调用就带着它——用来改方向；</li>
 *     <li>{@link #FOLLOW_UP} 插在模型<b>本来要收敛那一刻</b>，让它不收敛、继续跑一轮——
 *     用来「干完这件接着干那件」。</li>
 * </ul>
 * 两者都在同一个回合内，都不新增回合、不新增助手消息、不影响回合的取消句柄与在途状态。
 *
 * @author zcd
 */
public enum DeliverAs {

    /**
     * 改变正在进行的工作。
     * <p>
     * 插入点：一轮工具批次之后、下一次模型调用之前。
     */
    STEER,

    /**
     * 干完这件接着干那件。
     * <p>
     * 插入点：模型本来要收敛那一刻（它已经不再要求工具调用）。若此时回合已经收敛完毕，
     * 动作失败——「回合早就结束了，插件此刻才想说话」不在本期的能力范围内。
     */
    FOLLOW_UP
}

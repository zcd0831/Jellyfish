package zcd.jellyfish.tui;

/**
 * 按键动作：外壳对一次按键的意图判定结果。
 * <p>
 * 引入这一层是为了把「哪个键是什么意思」与「动作怎么执行」分开：
 * 判定是纯函数、可单测；执行需要终端与会话，只能端到端验证。
 *
 * @author zcd
 */
public enum InputAction {

    /** 发送当前输入。 */
    SEND,

    /** 中断进行中的回合。 */
    CANCEL,

    /** 退出外壳。 */
    QUIT,

    /**
     * 展开 / 折叠思考过程。
     * <p>
     * 全局开关（{@code Ctrl+T}）：没有「选中某条消息」的交互模型，逐块展开无从下手，
     * 而用户想要的是「一堆思考要么都看、要么都不看」。
     */
    TOGGLE_THINKING,

    /**
     * 展开 / 折叠工具调用参数。
     * <p>
     * 全局开关（{@code Ctrl+E} / {@code /toolargs}）：参数默认只折行到固定行数上限，
     * 超出部分收尾成一行省略提示；展开后把上限放宽，让长命令与 heredoc 能整段读完。
     * <p>
     * 与 {@link #TOGGLE_THINKING} 一样是全局而不是逐条：屏幕上没有「选中某个工具调用」的交互模型。
     */
    TOGGLE_TOOL_ARGS,

    /** 消息区上翻一页。 */
    PAGE_UP,

    /** 消息区下翻一页。 */
    PAGE_DOWN,

    /**
     * 消息区向上滚动若干行（滚轮一格）。
     * <p>
     * 与 {@link #PAGE_UP} 的区别只在步长：翻页按可见行数减一，滚轮按
     * {@link MouseScrollMapper#WHEEL_STEP_ROWS}。两者都归 {@link ChatState} 的滚动状态管，
     * 因此跟随/回底语义完全一致。
     */
    SCROLL_UP,

    /** 消息区向下滚动若干行（滚轮一格）。 */
    SCROLL_DOWN,

    /** 消息区跳到末尾并恢复跟随。 */
    TO_BOTTOM,

    /** 补全候选上移一项（仅补全面板可见时归外壳管）。 */
    COMPLETE_PREV,

    /** 补全候选下移一项（仅补全面板可见时归外壳管）。 */
    COMPLETE_NEXT,

    /**
     * 确认当前浮层面板的选中项（仅面板可见时归外壳管）。
     * <p>
     * {@code Enter} 映射到这里。补全面板可见时意为「把选中命令回填进输入框」，
     * 二级选择页可见时意为「执行选中的取值」；面板没弹时外壳返回 {@code UNHANDLED}，
     * 它就落回输入框当换行（T5 的反转键位不受影响）。
     */
    COMPLETE_ACCEPT,

    /**
     * 交还 / 收回鼠标（{@code Ctrl+O}，同 {@code /mouse}）。
     * <p>
     * <b>为什么值得占一个键位</b>：它是「想复制一段回答」时唯一的入口，而复制往往发生在读完一段长文本之后——
     * 那时再手敲一条命令既慢又打断阅读。做成单键之后，用户不必记住捕获与选择的得失，按一下、选、再按一下。
     * <p>
     * 与 {@link #TOGGLE_THINKING} 不同的是，它在<b>任何上下文</b>里都生效（含审批浮层与二级选择页）：
     * 它改的是终端能力，不是界面状态，因此不受「模态吞掉一切」的约束。
     */
    TOGGLE_MOUSE,

    /**
     * 不归外壳管，交给输入框编辑。
     * <p>
     * {@code Enter} 属于这一类——T5 采用反转键位，它是换行键而不是发送键。
     */
    EDIT
}

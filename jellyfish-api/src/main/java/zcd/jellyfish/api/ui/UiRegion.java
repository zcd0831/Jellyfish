package zcd.jellyfish.api.ui;

/**
 * 插件希望自己的面板落到的区域：<b>软建议，不是位置</b>。
 * <p>
 * <b>为什么是建议</b>：插件看不到终端有多宽，也不知道别的插件已经占了什么，「我想放左栏」这个决定
 * 在插件侧没有依据。区域是外壳的布局能力，也是多插件之间的竞争资源，因此必须有仲裁者——
 * 仲裁者是外壳与用户（用户用 {@code /ui} 切换）。外壳<b>可以完全忽略</b>这个建议，插件不得假设
 * 「我指定了就一定在那里」。
 * <p>
 * <b>为什么区域不在扩展点里而在这里当枚举</b>：正因为它是建议，外壳加一个新区域（例如再分一行）
 * <b>不需要</b> api 先加枚举值——插件给 {@code null} 就走默认区域，外壳自己决定往哪儿放。
 * 这个枚举只是让插件「有机会表达偏好」，不是位置清单。
 * <p>
 * <b>旧外壳遇到新枚举值</b>（新插件配旧外壳）时按默认区域处理，不报错。
 *
 * @author zcd
 */
public enum UiRegion {

    /** 状态栏所在的单行区域（拼接型，实际上由 {@code StatusLineContribution} 占用）。 */
    STATUS,

    /** 消息区与输入框之间的横向区域：最通用的面板落点。 */
    DOCK,

    /** 消息区上方的横向区域。 */
    TOP,

    /** 消息区左侧的纵向区域。 */
    LEFT,

    /** 消息区右侧的纵向区域。 */
    RIGHT
}

package zcd.jellyfish.core.subagent;

/**
 * 一次子代理委派的终态。
 * <p>
 * <b>为什么把「没跑起来」与「跑起来但失败」分开</b>：两者的可修复性完全不同——{@code REJECTED}
 * 是调用方（模型）换个参数、换个时机就能重试的，{@code FAILED} 则是运行期真的出了问题。
 * 把它们压成一个「失败」会让模型对「未知的子代理类型」这种自己写错的参数也去「重试一遍」，
 * 而提示文本也没法写出该改什么。
 *
 * @author zcd
 */
public enum SubAgentStatus {

    /** 子代理给出了最终回复。 */
    COMPLETED,

    /** 子代理达到自己的轮数上限仍未收敛，文本是内核给的提示。 */
    TRUNCATED,

    /** 子代理回合被取消（父回合被取消或用户中断）。 */
    CANCELLED,

    /** 委派已经开始，但子代理回合失败（模型不可用、会话异常……）。 */
    FAILED,

    /** 委派根本没有开始：开关关闭、层数/预算用尽、类型未知或不可委派。 */
    REJECTED
}
